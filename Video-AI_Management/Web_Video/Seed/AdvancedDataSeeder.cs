    private readonly HttpClient _httpClient;

    private const string ROOT_PATH = @"D:\ALLVIDEOS";
    private const string FFMPEG_PATH = @"C:\FFmpeg\ffmpeg\bin";

    public AdvancedDataSeeder(DataContext context, UserManager<AppUser> userManager, RoleManager<AppRole> roleManager, IWebHostEnvironment env)
    {
        _context = context;
        _userManager = userManager;
        _roleManager = roleManager;
